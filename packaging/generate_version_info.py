from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
VERSION_FILE = ROOT / "packaging" / "version.txt"
OUTPUT_FILE = ROOT / "packaging" / "windows-version-info.txt"
VERSION_PATTERN = re.compile(
    r"^(?P<major>0|[1-9]\d*)\.(?P<minor>0|[1-9]\d*)\.(?P<patch>0|[1-9]\d*)"
    r"$"
)


def render(version: str) -> str:
    match = VERSION_PATTERN.fullmatch(version)
    if not match:
        raise SystemExit(
            f"{VERSION_FILE} must contain a semantic version such as 1.2.3; got {version!r}"
        )

    numeric = tuple(int(match.group(name)) for name in ("major", "minor", "patch"))
    file_version = (*numeric, 0)

    return f"""# Generated by packaging/generate_version_info.py from packaging/version.txt.
# Regenerate this file before every Windows build.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={file_version},
    prodvers={file_version},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        u'040904B0',
        [
          StringStruct(u'CompanyName', u'Focus Capsule Project'),
          StringStruct(u'FileDescription', u'Focus Capsule desktop application'),
          StringStruct(u'FileVersion', u'{version}.0'),
          StringStruct(u'InternalName', u'FocusCapsule'),
          StringStruct(u'LegalCopyright', u'Copyright (c) 2026 Focus Capsule contributors'),
          StringStruct(u'OriginalFilename', u'Focus Capsule.exe'),
          StringStruct(u'ProductName', u'Focus Capsule'),
          StringStruct(u'ProductVersion', u'{version}')
        ]
      )
    ]),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the Windows PE version resource.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when the committed version resource is stale instead of rewriting it.",
    )
    args = parser.parse_args()

    expected = render(VERSION_FILE.read_text(encoding="utf-8").strip())
    if args.check:
        actual = OUTPUT_FILE.read_text(encoding="utf-8") if OUTPUT_FILE.exists() else ""
        if actual != expected:
            raise SystemExit(
                "packaging/windows-version-info.txt is stale; run "
                "python packaging/generate_version_info.py"
            )
        print("packaging/windows-version-info.txt is current")
        return 0

    OUTPUT_FILE.write_text(expected, encoding="utf-8", newline="\n")
    print("Wrote packaging/windows-version-info.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
